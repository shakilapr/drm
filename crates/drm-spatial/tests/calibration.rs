//! Live-calibration, generational-handle, and single-writer suite
//! (`cargo test -p drm-spatial calibration`): a calibration-slot update
//! invalidates dependent caches live with no recompilation or restart (`I-Q11`),
//! deleting a runtime overlay frame invalidates its outstanding generational
//! handles immediately (`I-Q12`/`I-S12`), and a second writer on a dynamic edge
//! is refused at runtime by the OS-backed authority lock (`I-S11`)
//! ([spatial-queries.md] §Test Matrix `spatial_calibration_live`,
//! `spatial_generational_edges`; [spatial-core.md] §Test Matrix
//! `spatial_single_writer`).
//!
//! REQ: REQ-SPATIAL-003, REQ-SPATIAL-011, REQ-SPATIAL-030, REQ-SPATIAL-016.

// Test fixtures convert between nanosecond integer stamps and `f64` geometry
// exactly for the small magnitudes used; the oracle fixture is JSON `f64`.
#![allow(
    clippy::cast_precision_loss,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss
)]

use drm_spatial::{
    CalibrationSlot, ClockDomain, ClockIdentity, EdgeSample, FLAG_DISCONTINUITY_NEARBY,
    HandleRegistry, QueryEngine, SpaceForest, SpatialError, SpatialHandle, TimeHistory, TimePoint,
    Transform3, acquire_edge_authority, correction_jump,
};
use serde_json::Value;

/// Oracle fixture generated by `tests/oracle/query_oracle.py`.
/// REQ: REQ-SPATIAL-003.
fn oracle() -> Value {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/fixtures/spatial/query_vectors.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| unreachable!("oracle: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| unreachable!("parse oracle: {e}"))
}

/// Reads a 3-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr3(v: &Value) -> [f64; 3] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
    ]
}

/// Reads a 4-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr4(v: &Value) -> [f64; 4] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
        a[3].as_f64().unwrap_or_default(),
    ]
}

/// Reads a JSON transform `{t, q}`.
/// REQ: REQ-SPATIAL-038.
fn tjson(v: &Value) -> Transform3 {
    Transform3::new(arr3(&v["t"]), arr4(&v["q"])).unwrap_or_else(|e| unreachable!("t: {e}"))
}

/// Asserts two transforms agree within `tol` (quaternions up to sign).
/// REQ: REQ-SPATIAL-036.
fn close(got: &Transform3, want: &Transform3, ctx: &str) {
    for i in 0..3 {
        assert!(
            (got.translation[i] - want.translation[i]).abs() < 1e-9,
            "{ctx}.t[{i}]: got {got:?} want {want:?}"
        );
    }
    let direct = (0..4).all(|i| (got.rotation[i] - want.rotation[i]).abs() < 1e-9);
    let negated = (0..4).all(|i| (got.rotation[i] + want.rotation[i]).abs() < 1e-9);
    assert!(direct || negated, "{ctx}.q: got {got:?} want {want:?}");
}

/// A host-monotonic [`TimePoint`].
/// REQ: REQ-SPATIAL-035.
fn host(ns: u64) -> TimePoint {
    TimePoint::new(ns, ClockIdentity::new(ClockDomain::HostMonotonic))
}

/// A static translation transform.
/// REQ: REQ-SPATIAL-038.
fn xyz(x: f64, y: f64, z: f64) -> Transform3 {
    Transform3 {
        translation: [x, y, z],
        rotation: [0.0, 0.0, 0.0, 1.0],
    }
}

/// A unique temporary directory per test.
/// REQ: REQ-SPATIAL-030.
fn tmpdir(tag: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "drm-swat-{}-{tag}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_nanos())
    ));
    std::fs::create_dir_all(&dir).unwrap_or_else(|e| unreachable!("tmpdir: {e}"));
    dir
}

/// REQ: REQ-SPATIAL-003 — `spatial_calibration_live`: a calibration-slot update
/// invalidates the cached geometry live and re-executes only plans containing
/// that slot, with no recompilation and no restart (`I-Q11`). The effective
/// transform matches `Nominal × Correction` against the oracle.
#[test]
fn spatial_calibration_live() {
    let doc = oracle();
    let cases = doc["calibration"]
        .as_array()
        .unwrap_or_else(|| unreachable!("calibration"));
    assert!(cases.len() >= 8);
    for case in cases {
        let nominal = tjson(&case["nominal"]);
        let corrections = case["corrections"]
            .as_array()
            .unwrap_or_else(|| unreachable!("corrections"));
        let c0 = tjson(&corrections[0]["correction"]);
        let c1 = tjson(&corrections[1]["correction"]);
        let e0 = corrections[0]["effective_ns"].as_u64().unwrap_or_default();
        let e1 = corrections[1]["effective_ns"].as_u64().unwrap_or_default();

        let mut forest = SpaceForest::new();
        forest.add_root("world".to_string());
        forest.add_dynamic("odom".to_string(), "world".to_string(), 0);
        let mut engine = QueryEngine::new(forest, 1);
        engine.attach_history(
            0,
            TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
        );
        engine.set_calibration(5, CalibrationSlot::new(nominal));
        engine
            .update_calibration_at(5, c0, e0, case["threshold"].as_f64().unwrap_or_default())
            .unwrap_or_else(|e| unreachable!("{e}"));
        let sample = EdgeSample::new(xyz(0.0, 0.0, 0.0), host(0), host(0));
        engine
            .publish(0, &sample)
            .unwrap_or_else(|e| unreachable!("{e}"));
        assert!(engine.latest("odom", "world").is_ok());
        let before = engine.compile_count();

        // The update bumps the slot version; the cache misses and the next query
        // re-executes with the new effective transform — no recompilation.
        engine
            .update_calibration_at(5, c1, e1, case["threshold"].as_f64().unwrap_or_default())
            .unwrap_or_else(|e| unreachable!("{e}"));
        let after = engine.latest("odom", "world");
        assert!(after.is_ok());
        assert_eq!(engine.compile_count(), before, "no recompilation on bump");

        // The slot's effective value matches the oracle. The engine plan here is
        // a single dynamic edge (no calibration step), so check the slot math
        // directly.
        let slot = engine
            .calibration(5)
            .copied()
            .unwrap_or_else(|| unreachable!("slot"));
        close(&slot.effective(), &tjson(&case["effective"]), "effective");

        // The correction jump matches the oracle, and the post-update slot is
        // flagged discontinuous iff the jump exceeded the threshold.
        let got_jump = correction_jump(&c0, &c1);
        assert!(
            (got_jump - case["jump"].as_f64().unwrap_or_default()).abs() < 1e-9,
            "jump: got {got_jump}"
        );
        assert_eq!(
            slot.discontinuous,
            case["discontinuous"].as_bool().unwrap_or_default()
        );
        // A flagged jump surfaces DISCONTINUITY_NEARBY on a query at/after it.
        if slot.discontinuous {
            assert!(engine.calibration_discontinuous_at(5, e1));
        }
    }
}

/// REQ: REQ-SPATIAL-003, REQ-SPATIAL-016 — a sub-threshold calibration update
/// clears a previously flagged jump (`I-Q7` tie-in).
#[test]
fn spatial_calibration_jump_threshold() {
    let nominal = xyz(1.0, 0.0, 0.0);
    let mut engine = QueryEngine::new(SpaceForest::new(), 0);
    engine.set_calibration(1, CalibrationSlot::new(nominal));
    // A large jump exceeds a tight threshold ⇒ flagged.
    engine
        .update_calibration_at(1, xyz(10.0, 0.0, 0.0), 100, 0.5)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let flagged = engine
        .calibration(1)
        .copied()
        .unwrap_or_else(|| unreachable!("slot"));
    assert!(flagged.discontinuous);
    assert!(engine.calibration_discontinuous_at(1, 100));
    assert!(!engine.calibration_discontinuous_at(1, 99));
    // A tiny follow-up clears the marker.
    engine
        .update_calibration_at(1, xyz(10.0, 0.0, 0.0), 200, 0.5)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let cleared = engine
        .calibration(1)
        .copied()
        .unwrap_or_else(|| unreachable!("slot"));
    assert!(!cleared.discontinuous);
    assert!(!engine.calibration_discontinuous_at(1, 200));
}

/// REQ: REQ-SPATIAL-011 — `spatial_generational_edges`: deleting a runtime
/// overlay frame invalidates its outstanding handle immediately (generation
/// bump, `I-Q12`/`I-S12`); the oracle gives the expected live generation.
#[test]
fn spatial_calibration_generational_edges() {
    let doc = oracle();
    let cases = doc["generational"]["cases"]
        .as_array()
        .unwrap_or_else(|| unreachable!("cases"));
    for case in cases {
        let frame = case["frame"].as_str().unwrap_or_default();
        let parent = case["parent"].as_str().unwrap_or_default();
        let reuse = case["reuse_frame"].as_str().unwrap_or_default();
        let expected = case["expected_generation"].as_u64().unwrap_or_default() as u32;
        let cycles = case["cycles"].as_u64().unwrap_or_default() as u32;

        let mut reg = HandleRegistry::new(4);
        // `cycles` create/delete rounds, each bumping the index generation once.
        let mut dead: Vec<SpatialHandle> = Vec::new();
        let first_index = 0_u32;
        for c in 0..cycles {
            let frame = if c == 0 { frame } else { reuse };
            let h = reg
                .create(frame, parent)
                .unwrap_or_else(|e| unreachable!("{e}"));
            assert_eq!(h.index, first_index, "index recycled");
            reg.delete(h).unwrap_or_else(|e| unreachable!("{e}"));
            dead.push(h);
        }
        for h in &dead {
            assert!(!reg.is_valid(*h), "outstanding handle invalidated");
            assert_eq!(reg.resolve(*h), Err(SpatialError::InvalidHandle));
        }
        let reused = reg
            .create(reuse, parent)
            .unwrap_or_else(|e| unreachable!("{e}"));
        assert_eq!(reused.index, first_index);
        assert_eq!(reused.generation, expected);
        assert!(reg.is_valid(reused));
        for h in &dead {
            assert!(!reg.is_valid(*h));
        }
    }
}

/// REQ: REQ-SPATIAL-011 — a stale handle is refused, and a made-up handle for a
/// freed index never resolves (`I-S12`).
#[test]
fn spatial_calibration_generational_stale_refused() {
    let mut reg = HandleRegistry::new(2);
    let h = reg
        .create("a", "map")
        .unwrap_or_else(|e| unreachable!("{e}"));
    reg.delete(h).unwrap_or_else(|e| unreachable!("{e}"));
    // Hand-forged previous-generation handle for the same index.
    let stale = SpatialHandle {
        index: h.index,
        generation: h.generation,
    };
    assert_eq!(reg.resolve(stale), Err(SpatialError::InvalidHandle));
    assert_eq!(reg.delete(stale), Err(SpatialError::InvalidHandle));
}

/// REQ: REQ-SPATIAL-030 — `spatial_single_writer`: a second writer on the same
/// dynamic edge is refused by the OS-backed authority lock (`I-S11`); distinct
/// edges never conflict; releasing authority lets a later writer take it.
#[test]
fn spatial_calibration_single_writer() {
    let dir = tmpdir("writer");
    let first = acquire_edge_authority(&dir, 0, 1).unwrap_or_else(|e| unreachable!("{e}"));
    assert_eq!(first.edge(), 0);
    assert_eq!(
        acquire_edge_authority(&dir, 0, 2).err(),
        Some(SpatialError::WriterConflict)
    );
    // A different edge is independent.
    let other = acquire_edge_authority(&dir, 1, 2).unwrap_or_else(|e| unreachable!("{e}"));
    assert_ne!(first.edge(), other.edge());
    drop(other);
    // Releasing the first edge lets a new writer take it.
    first.release().unwrap_or_else(|e| unreachable!("{e}"));
    let reacquired = acquire_edge_authority(&dir, 0, 3).unwrap_or_else(|e| unreachable!("{e}"));
    assert_eq!(reacquired.node(), 3);
    drop(reacquired);
    std::fs::remove_dir_all(&dir).unwrap_or_else(|e| unreachable!("cleanup: {e}"));
}

/// REQ: REQ-SPATIAL-003 — the effective transform is exactly `Nominal ×
/// Correction` for the identity correction (a newly-registered slot).
#[test]
fn spatial_calibration_identity_effective() {
    let nominal = xyz(2.0, -1.0, 0.5);
    let slot = CalibrationSlot::new(nominal);
    close(&slot.effective(), &nominal, "identity correction");
}

/// REQ: REQ-SPATIAL-003, REQ-SPATIAL-016 — a plan containing a calibration slot
/// re-executes live when the slot version bumps (no recompilation), and a
/// flagged jump surfaces `DISCONTINUITY_NEARBY` on the query result (`I-Q11`,
/// `I-Q7` tie-in).
#[test]
fn spatial_calibration_in_plan_live() {
    let nominal = xyz(1.0, 0.0, 0.0);
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_calibration("cam".to_string(), "world".to_string(), nominal, 5)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let mut engine = QueryEngine::new(forest, 0);
    engine.set_calibration(5, CalibrationSlot::new(nominal));
    // First query compiles once and caches geometry at correction=identity. The
    // query folds the path `world <- cam`, so the single calibrated edge appears
    // inverted (`T_world,cam = T_cam,world⁻¹`).
    let first = engine.latest("cam", "world");
    assert!(first.is_ok());
    let before = engine.compile_count();
    close(
        &first.transform.unwrap_or_else(|| unreachable!("t")),
        &drm_spatial::invert(&nominal),
        "identity",
    );
    // A live slot bump invalidates the cache; the same compiled plan re-executes
    // with the new correction. No recompilation, no restart.
    engine
        .update_calibration_at(5, xyz(0.5, 0.0, 0.0), 300, 0.1)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let after = engine.latest("cam", "world");
    assert!(after.is_ok());
    assert_eq!(engine.compile_count(), before, "no recompilation on bump");
    // Effective = nominal × correction = [1,0,0] ∘ [0.5,0,0] translation sum,
    // then inverted for the queried direction ⇒ -1.5.
    let got = after.transform.unwrap_or_else(|| unreachable!("t"));
    assert!(
        (got.translation[0] - -1.5).abs() < 1e-12,
        "got {:?}",
        got.translation
    );
    // The jump exceeded the threshold ⇒ the result carries the discontinuity flag.
    assert!(after.flags.contains(FLAG_DISCONTINUITY_NEARBY));
    // A sub-threshold update clears the marker; the query is clean again.
    engine
        .update_calibration_at(5, xyz(0.5, 0.0, 0.0), 400, 0.1)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let clean = engine.latest("cam", "world");
    assert!(!clean.flags.contains(FLAG_DISCONTINUITY_NEARBY));
}
