//! Clock-domain mapping suite (`cargo test -p drm-spatial clocks`) vs the
//! independent E4 clock oracle (`tests/oracle/clock_oracle.py`): four-domain
//! affine mapping, drift application, bounded uncertainty propagation, and
//! unresolved rejection (`I-S6`/`I-S7`, [spatial-core.md] §Temporal Precision).
//!
//! REQ: REQ-SPATIAL-004, REQ-SPATIAL-041, REQ-SPATIAL-051, REQ-SPATIAL-035.

use drm_spatial::{
    ClockDomain, ClockIdentity, ClockMapping, ClockTable, GlobalSource, TimePoint, map_timestamp,
    map_timestamp_with_uncertainty,
};
use serde_json::Value;

/// The committed oracle fixture generated by `tests/oracle/clock_oracle.py`.
/// REQ: REQ-SPATIAL-041.
fn oracle() -> Value {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/fixtures/spatial/clock_vectors.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| unreachable!("oracle: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| unreachable!("parse oracle: {e}"))
}

/// Reads an `i64` field.
/// REQ: REQ-SPATIAL-041.
fn i64of(v: &Value, key: &str) -> i64 {
    v[key].as_i64().unwrap_or_else(|| unreachable!("{key}"))
}

/// Reads an `f64` field.
/// REQ: REQ-SPATIAL-041.
fn f64of(v: &Value, key: &str) -> f64 {
    v[key].as_f64().unwrap_or_else(|| unreachable!("{key}"))
}

/// Builds a [`ClockMapping`] from an oracle mapping object targeting
/// `HostMonotonic`.
/// REQ: REQ-SPATIAL-041.
fn mapping_of(m: &Value) -> ClockMapping {
    ClockMapping {
        to: ClockIdentity::new(ClockDomain::HostMonotonic),
        from_ref_ns: i64of(m, "from_ref_ns"),
        to_ref_ns: i64of(m, "to_ref_ns"),
        rate_ratio: f64of(m, "rate_ratio"),
        uncertainty_at_ref_ns: m["uncertainty_at_ref_ns"].as_u64().unwrap_or_default(),
        uncertainty_growth: f64of(m, "uncertainty_growth"),
        valid_from_ns: i64of(m, "valid_from_ns"),
        valid_until_ns: i64of(m, "valid_until_ns"),
        generation: 1,
    }
}

/// REQ: REQ-SPATIAL-004, REQ-SPATIAL-041 — every oracle case maps to the same
/// instant and uncertainty, and out-of-validity cases are unresolved (`I-S7`).
#[test]
fn clocks_oracle_mapping() {
    let doc = oracle();
    let cases = doc["cases"]
        .as_array()
        .unwrap_or_else(|| unreachable!("cases"));
    assert!(!cases.is_empty());
    for case in cases {
        let m = case["mapping"]
            .as_object()
            .map_or_else(|| unreachable!("mapping"), |_| mapping_of(&case["mapping"]));
        let from = ClockIdentity::new(ClockDomain::Device(3));
        let mut table = ClockTable::new();
        table.insert(from, m);
        let t_from = i64of(case, "t_from_ns");
        let resolved = case["resolved"].as_bool().unwrap_or(false);
        let Ok(t_from_u) = u64::try_from(t_from) else {
            // A negative source instant is not representable as a `TimePoint`;
            // the oracle must agree it is unresolved.
            assert!(!resolved, "negative t_from must be unresolved");
            continue;
        };
        let t = TimePoint::new(t_from_u, from);
        if resolved {
            let (out, unc) = map_timestamp_with_uncertainty(t, ClockDomain::HostMonotonic, &table)
                .unwrap_or_else(|e| unreachable!("{e}"));
            assert_eq!(
                out.value_ns,
                u64::try_from(i64of(case, "t_to_ns")).unwrap_or_default(),
                "mapped instant mismatch"
            );
            assert_eq!(unc, case["uncertainty_ns"].as_u64().unwrap_or_default());
            assert_eq!(out.clock.domain, ClockDomain::HostMonotonic);
        } else {
            assert_eq!(
                map_timestamp(t, ClockDomain::HostMonotonic, &table),
                Err(drm_spatial::SpatialError::ClockUnresolved)
            );
        }
    }
}

/// REQ: REQ-SPATIAL-004 — all four clock domains are distinct identities and
/// `Global` distinguishes `PTP` from `GNSS`.
#[test]
fn clocks_four_domains_distinct() {
    let domains = [
        ClockDomain::HostMonotonic,
        ClockDomain::Device(1),
        ClockDomain::Global(GlobalSource::Ptp),
        ClockDomain::Global(GlobalSource::Gnss),
        ClockDomain::SimReplay,
    ];
    for (i, a) in domains.iter().enumerate() {
        for (j, b) in domains.iter().enumerate() {
            assert_eq!(a == b, i == j, "{a:?} vs {b:?}");
        }
    }
}

/// REQ: REQ-SPATIAL-051 — an epoch bump invalidates the prior mapping so an old
/// mapping never applies to a new clock incarnation (`I-S7`).
#[test]
fn clocks_epoch_bump_invalidates() {
    let mut table = ClockTable::new();
    let old = ClockIdentity {
        domain: ClockDomain::Device(5),
        epoch: 1,
    };
    table.insert(
        old,
        ClockMapping {
            to: ClockIdentity::new(ClockDomain::HostMonotonic),
            from_ref_ns: 0,
            to_ref_ns: 0,
            rate_ratio: 1.0,
            uncertainty_at_ref_ns: 0,
            uncertainty_growth: 0.0,
            valid_from_ns: 0,
            valid_until_ns: 1_000_000,
            generation: 1,
        },
    );
    let bumped = ClockIdentity {
        domain: ClockDomain::Device(5),
        epoch: 2,
    };
    assert_eq!(
        map_timestamp(
            TimePoint::new(10, bumped),
            ClockDomain::HostMonotonic,
            &table
        ),
        Err(drm_spatial::SpatialError::ClockUnresolved)
    );
}

/// REQ: REQ-SPATIAL-032, REQ-SPATIAL-041 — the mapping's propagated uncertainty
/// populates `TransformResult.clock_uncertainty_ns` (E2-T2).
#[test]
fn clocks_uncertainty_into_result() {
    let mut table = ClockTable::new();
    let from = ClockIdentity::new(ClockDomain::Global(GlobalSource::Gnss));
    table.insert(
        from,
        ClockMapping {
            to: ClockIdentity::new(ClockDomain::HostMonotonic),
            from_ref_ns: 0,
            to_ref_ns: 0,
            rate_ratio: 1.0,
            uncertainty_at_ref_ns: 42,
            uncertainty_growth: 0.0,
            valid_from_ns: 0,
            valid_until_ns: 1_000,
            generation: 1,
        },
    );
    let (_, uncertainty) = map_timestamp_with_uncertainty(
        TimePoint::new(10, from),
        ClockDomain::HostMonotonic,
        &table,
    )
    .unwrap_or_else(|e| unreachable!("{e}"));
    let result = drm_spatial::TransformResult::ok(drm_spatial::Transform3::IDENTITY, uncertainty);
    assert_eq!(result.clock_uncertainty_ns, 42);
    assert!(result.is_ok());
}

/// REQ: REQ-SPATIAL-041 — uncertainty grows monotonically with elapsed time and
/// never shrinks below the reference value.
#[test]
fn clocks_uncertainty_monotonic() {
    let mut table = ClockTable::new();
    let from = ClockIdentity::new(ClockDomain::Global(GlobalSource::Ptp));
    let mapping = ClockMapping {
        to: ClockIdentity::new(ClockDomain::HostMonotonic),
        from_ref_ns: 0,
        to_ref_ns: 0,
        rate_ratio: 1.0,
        uncertainty_at_ref_ns: 20,
        uncertainty_growth: 0.000_1,
        valid_from_ns: 0,
        valid_until_ns: 1_000_000_000,
        generation: 1,
    };
    table.insert(from, mapping);
    let mut prev = 0_u64;
    for t in [0_u64, 1_000, 10_000, 100_000, 1_000_000] {
        let (_, unc) = map_timestamp_with_uncertainty(
            TimePoint::new(t, from),
            ClockDomain::HostMonotonic,
            &table,
        )
        .unwrap_or_else(|e| unreachable!("{e}"));
        assert!(unc >= prev, "uncertainty must not shrink");
        assert!(unc >= mapping.uncertainty_at_ref_ns);
        prev = unc;
    }
}
