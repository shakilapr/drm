//! Query-API suite (`cargo test -p drm-spatial queries`):
//! `latest`/`at`/`predict`/`delayed_view` against the independent E4 query
//! oracle (`tests/oracle/query_oracle.py`), the plan-execution invariant, and
//! the interpolation numerics ([spatial-queries.md] §Test Matrix, I-Q1..I-Q6).
//!
//! REQ: REQ-SPATIAL-022, REQ-SPATIAL-023, REQ-SPATIAL-024, REQ-SPATIAL-025,
//! REQ-SPATIAL-034, REQ-SPATIAL-016, REQ-SPATIAL-002.

// Test fixtures convert between nanosecond integer stamps and `f64` geometry
// exactly for the small magnitudes used; the oracle fixture is JSON `f64`.
#![allow(
    clippy::cast_precision_loss,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss
)]

use drm_spatial::{
    CalibrationSlot, ClockDomain, ClockIdentity, EdgeSample, FLAG_DISCONTINUITY_NEARBY,
    FLAG_EXTRAPOLATED, QueryEngine, SpaceForest, SpatialEdgeCache, TimeHistory, TimePoint,
    Transform3, Twist3, Vector3, WriterClaim,
};
use serde_json::Value;

/// Oracle fixture generated by `tests/oracle/query_oracle.py`.
/// REQ: REQ-SPATIAL-022.
fn oracle() -> Value {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/fixtures/spatial/query_vectors.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| unreachable!("oracle: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| unreachable!("parse oracle: {e}"))
}

/// Reads a 3-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr3(v: &Value) -> [f64; 3] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
    ]
}

/// Reads a 4-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr4(v: &Value) -> [f64; 4] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
        a[3].as_f64().unwrap_or_default(),
    ]
}

/// Reads a JSON transform `{t, q}`.
/// REQ: REQ-SPATIAL-038.
fn tjson(v: &Value) -> Transform3 {
    Transform3::new(arr3(&v["t"]), arr4(&v["q"])).unwrap_or_else(|e| unreachable!("t: {e}"))
}

/// Asserts two transforms agree within `tol` (quaternions up to sign).
/// REQ: REQ-SPATIAL-036.
fn close(got: &Transform3, want: &Transform3, ctx: &str) {
    for i in 0..3 {
        assert!(
            (got.translation[i] - want.translation[i]).abs() < 1e-9,
            "{ctx}.t[{i}]: got {got:?} want {want:?}"
        );
    }
    let direct = (0..4).all(|i| (got.rotation[i] - want.rotation[i]).abs() < 1e-9);
    let negated = (0..4).all(|i| (got.rotation[i] + want.rotation[i]).abs() < 1e-9);
    assert!(direct || negated, "{ctx}.q: got {got:?} want {want:?}");
}

/// A host-monotonic [`TimePoint`].
/// REQ: REQ-SPATIAL-035.
fn host(ns: u64) -> TimePoint {
    TimePoint::new(ns, ClockIdentity::new(ClockDomain::HostMonotonic))
}

/// A static translation transform.
/// REQ: REQ-SPATIAL-038.
fn xyz(x: f64, y: f64, z: f64) -> Transform3 {
    Transform3 {
        translation: [x, y, z],
        rotation: [0.0, 0.0, 0.0, 1.0],
    }
}

/// A forest with one dynamic edge (`odom` under `world`, edge `0`).
/// REQ: REQ-SPATIAL-010.
fn one_edge_engine() -> QueryEngine {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest.add_dynamic("odom".to_string(), "world".to_string(), 0);
    let mut engine = QueryEngine::new(forest, 1);
    engine.attach_history(
        0,
        TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
    );
    engine
}

/// Publishes a translation sample on edge `0`.
/// REQ: REQ-SPATIAL-033.
fn publish(engine: &mut QueryEngine, t_ns: u64, x: f64) {
    let sample = EdgeSample::new(xyz(x, 0.0, 0.0), host(t_ns), host(t_ns));
    engine
        .publish(0, &sample)
        .unwrap_or_else(|e| unreachable!("{e}"));
}

/// REQ: REQ-SPATIAL-034 — `spatial_plan_execution`: repeated runtime queries
/// never re-traverse the base graph; the plan compiles exactly once (`I-Q1`).
#[test]
fn queries_plan_execution() {
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 0.0);
    publish(&mut engine, 100, 10.0);
    let _ = engine.latest("odom", "world");
    let _ = engine.at("odom", "world", 50);
    let _ = engine.at("odom", "world", 25);
    let _ = engine.latest("odom", "world");
    assert_eq!(
        engine.compile_count(),
        1,
        "plan compiled once, never walked"
    );
}

/// REQ: REQ-SPATIAL-024 — `spatial_query_latest`: multiple asynchronous edges
/// resolve at the single common coherent timestamp `t* = min_i(t_newest,i)`
/// (`I-Q3`).
#[test]
fn queries_latest() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest.add_dynamic("a".to_string(), "world".to_string(), 0);
    forest.add_dynamic("b".to_string(), "world".to_string(), 1);
    forest
        .add_static("c".to_string(), "world".to_string(), xyz(0.0, 0.0, 1.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    // Query c relative to b: path b -> world -> c. c is static.
    let mut engine = QueryEngine::new(forest, 2);
    engine.attach_history(
        0,
        TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
    );
    engine.attach_history(
        1,
        TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
    );

    // Edge a advances to 50, edge b only to 30 ⇒ t* = 30.
    for (e, t) in [(0_u32, 0_u64), (0, 10), (0, 20), (0, 30), (0, 40), (0, 50)] {
        let sample = EdgeSample::new(xyz(t as f64, 0.0, 0.0), host(t), host(t));
        engine
            .publish(e, &sample)
            .unwrap_or_else(|e| unreachable!("{e}"));
    }
    for t in [0_u64, 10, 20, 30] {
        let sample = EdgeSample::new(xyz(0.0, t as f64, 0.0), host(t), host(t));
        engine
            .publish(1, &sample)
            .unwrap_or_else(|e| unreachable!("{e}"));
    }
    let res = engine.latest("a", "b");
    assert!(res.is_ok(), "coherent intersection exists");
    assert_eq!(res.sample_time.map(|t| t.value_ns), Some(30));
}

/// REQ: REQ-SPATIAL-022 — `spatial_query_at`: `at` interpolates between brackets
/// against the oracle and never silently extrapolates (`I-Q4`).
#[test]
fn queries_at() {
    let doc = oracle();
    let cases = doc["interp"]
        .as_array()
        .unwrap_or_else(|| unreachable!("interp"));
    assert!(cases.len() >= 10);
    for case in cases {
        let a = tjson(&case["a"]);
        let b = tjson(&case["b"]);
        let frac = case["frac"].as_f64().unwrap_or_default();
        let want = tjson(&case["expected"]);
        // The interpolation helper `at` uses: linear translation + SLERP.
        let got = drm_spatial::interpolate_transform(&a, &b, frac);
        close(&got, &want, "interp");
    }

    // The `at` path brackets samples in a sample-time-ordered history and never
    // extrapolates beyond the newest sample.
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 0.0);
    publish(&mut engine, 100, 10.0);
    let mid = engine.at("odom", "world", 50);
    assert!((mid.transform.map(|t| t.translation[0]).unwrap_or_default() - 5.0).abs() < 1e-9);
    assert_eq!(
        engine.at("odom", "world", 101).error,
        Some(drm_spatial::TransformError::OutOfHistory)
    );
    assert_eq!(
        engine
            .at("odom", "world", 0)
            .transform
            .map(|t| t.translation[0]),
        Some(0.0)
    );
}

/// REQ: REQ-SPATIAL-025 — `spatial_predict_screw`: the exponential-map
/// integration matches the independent screw-motion oracle, and beyond the
/// declared horizon returns `OUT_OF_HISTORY` (`I-Q5`).
#[test]
fn queries_predict_screw() {
    let doc = oracle();
    let cases = doc["predict"]
        .as_array()
        .unwrap_or_else(|| unreachable!("predict"));
    assert!(cases.len() >= 10);
    for case in cases {
        let base = tjson(&case["base"]);
        let twist = Twist3 {
            linear: Vector3::new(
                case["twist"]["linear"][0].as_f64().unwrap_or_default(),
                case["twist"]["linear"][1].as_f64().unwrap_or_default(),
                case["twist"]["linear"][2].as_f64().unwrap_or_default(),
            )
            .unwrap_or_default(),
            angular: Vector3::new(
                case["twist"]["angular"][0].as_f64().unwrap_or_default(),
                case["twist"]["angular"][1].as_f64().unwrap_or_default(),
                case["twist"]["angular"][2].as_f64().unwrap_or_default(),
            )
            .unwrap_or_default(),
        };
        let dt = case["dt"].as_f64().unwrap_or_default();
        let want_delta = tjson(&case["delta"]);
        let got_delta = drm_spatial::exp_twist(&twist, dt).unwrap_or_else(|e| unreachable!("{e}"));
        close(&got_delta, &want_delta, "exp_twist");

        // Against the engine: predict composes base ∘ delta and flags EXTRAPOLATED.
        let mut engine = one_edge_engine();
        let sample = EdgeSample::new(base, host(0), host(0));
        engine
            .publish(0, &sample)
            .unwrap_or_else(|e| unreachable!("{e}"));
        engine.set_max_horizon(u64::MAX);
        engine.set_predict_twist(twist);
        let horizon_ns = (dt * 1e9).round() as u64;
        let res = engine.predict("odom", "world", horizon_ns);
        assert!(res.flags.contains(FLAG_EXTRAPOLATED));
        let got = res.transform.unwrap_or_else(|| unreachable!("transform"));
        close(&got, &drm_spatial::compose(&base, &want_delta), "predict");
    }

    // Bounded: beyond max_horizon ⇒ OUT_OF_HISTORY without a value.
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 1.0);
    engine.set_max_horizon(100);
    let res = engine.predict("odom", "world", 101);
    assert!(!res.is_ok());
    assert_eq!(res.error, Some(drm_spatial::TransformError::OutOfHistory));
}

/// REQ: REQ-SPATIAL-023 — `spatial_delayed_view`: a trailing view resolves
/// `at(now − offset)`; an offset beyond retained history ⇒ `OUT_OF_HISTORY`
/// (`I-Q6`).
#[test]
fn queries_delayed_view() {
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 0.0);
    publish(&mut engine, 100, 10.0);
    engine.set_now(100);
    let mid = engine.delayed_view("odom", "world", 50);
    assert!((mid.transform.map(|t| t.translation[0]).unwrap_or_default() - 5.0).abs() < 1e-9);
    assert_eq!(
        engine.delayed_view("odom", "world", 200).error,
        Some(drm_spatial::TransformError::OutOfHistory)
    );
}

/// REQ: REQ-SPATIAL-016 — `spatial_interp_guard`: interpolation across a flagged
/// discontinuity is refused and surfaces `DISCONTINUITY_NEARBY`
/// (`I-Q7`).
#[test]
fn queries_interp_guard() {
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 0.0);
    // A relocalization: the sample at t=100 jumps and is flagged discontinuous.
    let jump = EdgeSample::new(xyz(100.0, 0.0, 0.0), host(100), host(100)).with_discontinuous();
    engine
        .publish(0, &jump)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let res = engine.at("odom", "world", 50);
    assert!(!res.is_ok(), "no cross-jump value");
    assert!(res.flags.contains(FLAG_DISCONTINUITY_NEARBY));
    // Exact endpoints remain resolvable.
    assert!(engine.at("odom", "world", 0).is_ok());
    assert!(engine.at("odom", "world", 100).is_ok());
}

/// REQ: REQ-SPATIAL-003 — `spatial_calibration_live`: a calibration-slot update
/// invalidates dependent caches live with no recompilation (`I-Q11`).
#[test]
fn queries_calibration_live() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest.add_dynamic("odom".to_string(), "world".to_string(), 0);
    let mut engine = QueryEngine::new(forest, 1);
    engine.attach_history(
        0,
        TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
    );
    engine.set_calibration(5, CalibrationSlot::new(xyz(1.0, 0.0, 0.0)));
    publish(&mut engine, 0, 0.0);
    assert!(engine.latest("odom", "world").is_ok());
    let before = engine.compile_count();
    engine
        .update_calibration(5, xyz(0.25, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    assert!(engine.latest("odom", "world").is_ok());
    assert_eq!(
        engine.compile_count(),
        before,
        "no recompilation on slot bump"
    );
}

/// REQ: REQ-SPATIAL-002 — `spatial_cache_aging`: unchanged input versions reuse
/// cached geometry, but freshness is still derived per query (`I-Q2`).
#[test]
fn queries_cache_aging() {
    let mut engine = one_edge_engine();
    engine.set_freshness(500);
    publish(&mut engine, 1_000, 7.0);
    engine.set_now(1_000);
    let fresh = engine.latest("odom", "world");
    assert!(!fresh.flags.contains(drm_spatial::FLAG_STALE));
    // Wall time advances with no new publish ⇒ STALE, geometry reused.
    engine.set_now(10_000_000);
    let aged = engine.latest("odom", "world");
    assert!(aged.flags.contains(drm_spatial::FLAG_STALE));
    assert!((aged.transform.map(|t| t.translation[0]).unwrap_or_default() - 7.0).abs() < 1e-12);
}

/// REQ: REQ-SPATIAL-024 — a fully static pair resolves through `latest` without
/// any dynamic input (`I-Q1`/`I-Q3`).
#[test]
fn queries_latest_static_pair() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_static(
            "sensor".to_string(),
            "world".to_string(),
            xyz(1.0, 2.0, 3.0),
        )
        .unwrap_or_else(|e| unreachable!("{e}"));
    let mut engine = QueryEngine::new(forest, 0);
    let res = engine.latest("sensor", "world");
    assert!(res.is_ok());
    let t = res.transform.unwrap_or_else(|| unreachable!("transform"));
    let norm =
        (t.translation[0].powi(2) + t.translation[1].powi(2) + t.translation[2].powi(2)).sqrt();
    assert!((norm - 14.0_f64.sqrt()).abs() < 1e-12);
    assert_eq!(engine.compile_count(), 1);
}

/// REQ: REQ-SPATIAL-050 — a two-edge plan uses two distinct writers (single
/// writer per dynamic edge, `I-S11`) without conflict.
#[test]
fn queries_two_writers() {
    let cache = SpatialEdgeCache::new(2);
    let w0: WriterClaim = cache
        .claim_writer(0, 1)
        .unwrap_or_else(|e| unreachable!("{e}"));
    let w1: WriterClaim = cache
        .claim_writer(1, 2)
        .unwrap_or_else(|e| unreachable!("{e}"));
    assert_ne!(w0.edge(), w1.edge());
    assert_eq!(
        cache.claim_writer(0, 3).err(),
        Some(drm_spatial::SpatialError::WriterConflict)
    );
}
