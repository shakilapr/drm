//! Discontinuity-guard and transactional-reparenting suite
//! (`cargo test -p drm-spatial interp_guard`, `... reparent`):
//! interpolation refusal across a flagged discontinuity (`I-Q7`), temporal
//! reparenting that never rewrites pre-`t₁` history (`I-Q8`), the three
//! Preserve World/Local/Snap modes (`I-Q9`), and atomic tree mutation (`I-Q10`)
//! against the independent E4 reparent oracle
//! (`tests/oracle/query_oracle.py`, [spatial-queries.md] §Test Matrix).
//!
//! REQ: REQ-SPATIAL-016, REQ-SPATIAL-027, REQ-SPATIAL-028, REQ-SPATIAL-029.

// Test fixtures convert between nanosecond integer stamps and `f64` geometry
// exactly for the small magnitudes used; the oracle fixture is JSON `f64`.
#![allow(
    clippy::cast_precision_loss,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss
)]

use drm_spatial::{
    ClockDomain, ClockIdentity, EdgeSample, FLAG_DISCONTINUITY_NEARBY, FrameEdge, QueryEngine,
    ReparentMode, SpaceForest, SpatialError, TimeHistory, TimePoint, Transform3,
};
use serde_json::Value;

/// Oracle fixture generated by `tests/oracle/query_oracle.py`.
/// REQ: REQ-SPATIAL-028.
fn oracle() -> Value {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/fixtures/spatial/query_vectors.json"
    );
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| unreachable!("oracle: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| unreachable!("parse oracle: {e}"))
}

/// Reads a 3-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr3(v: &Value) -> [f64; 3] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
    ]
}

/// Reads a 4-element `f64` array.
/// REQ: REQ-SPATIAL-036.
fn arr4(v: &Value) -> [f64; 4] {
    let a = v.as_array().unwrap_or_else(|| unreachable!("array"));
    [
        a[0].as_f64().unwrap_or_default(),
        a[1].as_f64().unwrap_or_default(),
        a[2].as_f64().unwrap_or_default(),
        a[3].as_f64().unwrap_or_default(),
    ]
}

/// Reads a JSON transform `{t, q}`.
/// REQ: REQ-SPATIAL-038.
fn tjson(v: &Value) -> Transform3 {
    Transform3::new(arr3(&v["t"]), arr4(&v["q"])).unwrap_or_else(|e| unreachable!("t: {e}"))
}

/// Asserts two transforms agree within `tol` (quaternions up to sign).
/// REQ: REQ-SPATIAL-036.
fn close(got: &Transform3, want: &Transform3, ctx: &str) {
    for i in 0..3 {
        assert!(
            (got.translation[i] - want.translation[i]).abs() < 1e-9,
            "{ctx}.t[{i}]: got {got:?} want {want:?}"
        );
    }
    let direct = (0..4).all(|i| (got.rotation[i] - want.rotation[i]).abs() < 1e-9);
    let negated = (0..4).all(|i| (got.rotation[i] + want.rotation[i]).abs() < 1e-9);
    assert!(direct || negated, "{ctx}.q: got {got:?} want {want:?}");
}

/// A host-monotonic [`TimePoint`].
/// REQ: REQ-SPATIAL-035.
fn host(ns: u64) -> TimePoint {
    TimePoint::new(ns, ClockIdentity::new(ClockDomain::HostMonotonic))
}

/// A static translation transform.
/// REQ: REQ-SPATIAL-038.
fn xyz(x: f64, y: f64, z: f64) -> Transform3 {
    Transform3 {
        translation: [x, y, z],
        rotation: [0.0, 0.0, 0.0, 1.0],
    }
}

/// A reparent fixture forest: `world` root, `old`/`new` static parents, and an
/// `obj` static child of `old` (`I-Q9`).
/// REQ: REQ-SPATIAL-028.
fn fixture_forest(
    t_anchor_old: Transform3,
    t_anchor_new: Transform3,
    t_old_obj: Transform3,
) -> SpaceForest {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_static("old".to_string(), "world".to_string(), t_anchor_old)
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
        .add_static("obj".to_string(), "old".to_string(), t_old_obj)
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
        .add_static("new".to_string(), "world".to_string(), t_anchor_new)
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
}

/// A one-dynamic-edge engine with a `TimeHistory` (`REQ-SPATIAL-033`).
/// REQ: REQ-SPATIAL-010.
fn one_edge_engine() -> QueryEngine {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest.add_dynamic("odom".to_string(), "world".to_string(), 0);
    let mut engine = QueryEngine::new(forest, 1);
    engine.attach_history(
        0,
        TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
    );
    engine
}

/// Publishes a translation sample on edge `0`.
/// REQ: REQ-SPATIAL-033.
fn publish(engine: &mut QueryEngine, t_ns: u64, x: f64) {
    let sample = EdgeSample::new(xyz(x, 0.0, 0.0), host(t_ns), host(t_ns));
    engine
        .publish(0, &sample)
        .unwrap_or_else(|e| unreachable!("{e}"));
}

/// REQ: REQ-SPATIAL-016 — `spatial_interp_guard`: relocalize, reparent, and
/// calibration-jump fixtures all refuse interpolation across the flagged
/// boundary with `DISCONTINUITY_NEARBY` while the exact endpoints stay valid
/// (`I-Q7`).
#[test]
fn spatial_interp_guard() {
    let doc = oracle();
    let cases = doc["discontinuity"]["cases"]
        .as_array()
        .unwrap_or_else(|| unreachable!("discontinuity"));
    assert!(cases.len() >= 3);
    for case in cases {
        let kind = case["kind"].as_str().unwrap_or_default();
        let jump_at = case["jump_at"].as_u64().unwrap_or_default();
        let query_t = case["query_t"].as_u64().unwrap_or_default();
        let mut engine = one_edge_engine();
        for sample in case["samples"]
            .as_array()
            .unwrap_or_else(|| unreachable!("samples"))
        {
            publish(
                &mut engine,
                sample["t"].as_u64().unwrap_or_default(),
                sample["x"].as_f64().unwrap_or_default(),
            );
        }
        assert!(
            engine.mark_discontinuity(0, jump_at),
            "{kind}: retained sample at jump must be marked"
        );
        let res = engine.at("odom", "world", query_t);
        assert!(!res.is_ok(), "{kind}: no cross-jump value");
        assert!(
            res.flags.contains(FLAG_DISCONTINUITY_NEARBY),
            "{kind}: DISCONTINUITY_NEARBY flag"
        );
        for t in case["endpoints_valid"]
            .as_array()
            .unwrap_or_else(|| unreachable!("endpoints"))
        {
            let t_ns = t.as_u64().unwrap_or_default();
            assert!(
                engine.at("odom", "world", t_ns).is_ok(),
                "{kind}: endpoint {t_ns}"
            );
        }
    }
}

/// REQ: REQ-SPATIAL-016 — the marker propagates to both the history ring and the
/// live edge slot, so a guard query and a slot read agree (`I-Q7`).
#[test]
fn spatial_interp_guard_slot_propagation() {
    let mut engine = one_edge_engine();
    publish(&mut engine, 0, 0.0);
    let jump = EdgeSample::new(xyz(50.0, 0.0, 0.0), host(100), host(100)).with_discontinuous();
    engine
        .publish(0, &jump)
        .unwrap_or_else(|e| unreachable!("{e}"));
    assert!(engine.is_discontinuity(0, 100));
    assert!(engine.edges().read(0).is_some_and(|s| s.is_discontinuous()));
}

/// REQ: REQ-SPATIAL-028 — `spatial_reparent_modes`: Preserve World, Preserve
/// Local, and Snap each compute the oracle's new local offset and resulting
/// anchor pose (`I-Q9`).
#[test]
fn spatial_reparent_modes() {
    let doc = oracle();
    let cases = doc["reparent"]
        .as_array()
        .unwrap_or_else(|| unreachable!("reparent"));
    assert!(cases.len() >= 10);
    for case in cases {
        let e_old = tjson(&case["e_old"]);
        let e_new = tjson(&case["e_new"]);
        let e_obj = tjson(&case["e_obj"]);
        let want_before = tjson(&case["anchor_pose_before"]);
        for (mode, name) in [
            (ReparentMode::PreserveWorld, "preserve_world"),
            (ReparentMode::PreserveLocal, "preserve_local"),
            (ReparentMode::Snap, "snap"),
        ] {
            let forest = fixture_forest(e_old, e_new, e_obj);
            let mut engine = QueryEngine::new(forest, 0);
            let before = engine.at("world", "obj", 0);
            close(
                &before.transform.unwrap_or_else(|| unreachable!("before")),
                &want_before,
                "anchor_pose_before",
            );
            engine
                .reparent("obj", "new", mode, 1000)
                .unwrap_or_else(|e| unreachable!("{e}"));
            let want = &case["modes"][name];
            let local = match engine.forest().edge("obj") {
                Some(FrameEdge::Static(t)) => t,
                other => unreachable!("expected static local edge, got {other:?}"),
            };
            close(&local, &tjson(&want["local"]), "local");
            let after = engine.at("world", "obj", 1500);
            close(
                &after.transform.unwrap_or_else(|| unreachable!("after")),
                &tjson(&want["anchor_pose"]),
                "anchor_pose",
            );
        }
    }
}

/// REQ: REQ-SPATIAL-028 — `spatial_reparent_world_continuity`: Preserve World
/// keeps the object's anchor pose continuous across the reparent instant
/// (`I-Q9`).
#[test]
fn spatial_reparent_world_continuity() {
    let doc = oracle();
    let cases = doc["reparent"]
        .as_array()
        .unwrap_or_else(|| unreachable!("reparent"));
    for case in cases {
        let forest = fixture_forest(
            tjson(&case["e_old"]),
            tjson(&case["e_new"]),
            tjson(&case["e_obj"]),
        );
        let mut engine = QueryEngine::new(forest, 0);
        let before = engine
            .at("world", "obj", 0)
            .transform
            .unwrap_or_else(|| unreachable!("before"));
        engine
            .reparent("obj", "new", ReparentMode::PreserveWorld, 1000)
            .unwrap_or_else(|e| unreachable!("{e}"));
        let after = engine
            .at("world", "obj", 1500)
            .transform
            .unwrap_or_else(|| unreachable!("after"));
        close(&after, &before, "world continuity");
    }
}

/// REQ: REQ-SPATIAL-029 — `spatial_reparent_temporal`: a reparent at `t₁` never
/// alters history before `t₁`; earlier queries traverse the original hierarchy
/// while later queries use the new one (`I-Q8`).
#[test]
fn spatial_reparent_temporal() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_static("old".to_string(), "world".to_string(), xyz(10.0, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
        .add_static("obj".to_string(), "old".to_string(), xyz(1.0, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
        .add_static("new".to_string(), "world".to_string(), xyz(0.0, 5.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    let mut engine = QueryEngine::new(forest, 0);

    // Register the original-hierarchy plan before the reparent.
    let before = engine
        .at("world", "obj", 100)
        .transform
        .unwrap_or_else(|| unreachable!("before"));
    assert!((before.translation[0] - 11.0).abs() < 1e-9);

    engine
        .reparent("obj", "new", ReparentMode::PreserveLocal, 1000)
        .unwrap_or_else(|e| unreachable!("{e}"));

    // Pre-t₁ query still traverses the original hierarchy.
    let historical = engine
        .at("world", "obj", 500)
        .transform
        .unwrap_or_else(|| unreachable!("historical"));
    assert!((historical.translation[0] - 11.0).abs() < 1e-9);
    assert!((historical.translation[1]).abs() < 1e-9);

    // Post-t₁ query uses the new hierarchy; Preserve Local keeps the 1 m offset.
    let current = engine
        .at("world", "obj", 1500)
        .transform
        .unwrap_or_else(|| unreachable!("current"));
    assert!((current.translation[0] - 1.0).abs() < 1e-9);
    assert!((current.translation[1] - 5.0).abs() < 1e-9);
}

/// REQ: REQ-SPATIAL-027 — `spatial_reparent_atomic`: a transaction stages
/// mutations and applies them all-or-nothing; an uncommitted or failed
/// transaction leaves the base forest untouched, so readers never observe a
/// partial tree (`I-Q10`).
#[test]
fn spatial_reparent_atomic() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_static("old".to_string(), "world".to_string(), xyz(10.0, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    forest
        .add_static("obj".to_string(), "old".to_string(), xyz(1.0, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    let original = match forest.edge("obj") {
        Some(FrameEdge::Static(t)) => t,
        other => unreachable!("expected static, got {other:?}"),
    };

    // A staged relink to an unknown parent fails and is never applied.
    {
        let mut txn = forest.begin();
        assert_eq!(
            txn.relink_static("obj".to_string(), "missing".to_string(), xyz(9.0, 0.0, 0.0)),
            Err(SpatialError::PathNotFound)
        );
    }
    // Dropping the transaction leaves the base unchanged.
    let unchanged = match forest.edge("obj") {
        Some(FrameEdge::Static(t)) => t,
        other => unreachable!("expected static, got {other:?}"),
    };
    close(&unchanged, &original, "uncommitted");

    // A committed transaction applies both relinks together.
    forest.add_root("world2".to_string());
    {
        let mut txn = forest.begin();
        txn.relink_static("obj".to_string(), "world2".to_string(), xyz(2.0, 0.0, 0.0))
            .unwrap_or_else(|e| unreachable!("{e}"));
        txn.relink_static("old".to_string(), "world2".to_string(), xyz(3.0, 0.0, 0.0))
            .unwrap_or_else(|e| unreachable!("{e}"));
        txn.commit(&mut forest);
    }
    let committed = match forest.edge("obj") {
        Some(FrameEdge::Static(t)) => t,
        other => unreachable!("expected static, got {other:?}"),
    };
    close(&committed, &xyz(2.0, 0.0, 0.0), "committed");
    assert_eq!(forest.parent("obj").map(String::as_str), Some("world2"));
    assert_eq!(forest.parent("old").map(String::as_str), Some("world2"));
}

/// REQ: REQ-SPATIAL-016, REQ-SPATIAL-028 — a reparent of a dynamic object flags
/// its jumped local edge discontinuous at `t₁` (`I-Q7`/`I-Q9`).
#[test]
fn spatial_reparent_marks_discontinuity() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest.add_dynamic("old".to_string(), "world".to_string(), 0);
    forest.add_dynamic("obj".to_string(), "old".to_string(), 1);
    forest
        .add_static("new".to_string(), "world".to_string(), xyz(0.0, 5.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    let mut engine = QueryEngine::new(forest, 2);
    for edge in [0_u32, 1] {
        engine.attach_history(
            edge,
            TimeHistory::new(12, 100, 10).unwrap_or_else(|e| unreachable!("{e}")),
        );
    }
    for edge in [0_u32, 1] {
        for t in [0_u64, 100] {
            let sample = EdgeSample::new(xyz(1.0, 0.0, 0.0), host(t), host(t));
            engine
                .publish(edge, &sample)
                .unwrap_or_else(|e| unreachable!("{e}"));
        }
    }
    engine
        .reparent("obj", "new", ReparentMode::PreserveWorld, 100)
        .unwrap_or_else(|e| unreachable!("{e}"));
    assert!(engine.is_discontinuity(1, 100), "jumped local edge flagged");
}

/// REQ: REQ-SPATIAL-027, REQ-SPATIAL-028 — reparenting an unknown or disconnected
/// object is rejected and leaves the tree intact (`I-Q10`).
#[test]
fn spatial_reparent_rejects_unknown() {
    let mut forest = SpaceForest::new();
    forest.add_root("world".to_string());
    forest
        .add_static("obj".to_string(), "world".to_string(), xyz(1.0, 0.0, 0.0))
        .unwrap_or_else(|e| unreachable!("{e}"));
    let mut engine = QueryEngine::new(forest, 0);
    assert_eq!(
        engine.reparent("obj", "missing", ReparentMode::Snap, 0),
        Err(SpatialError::PathNotFound)
    );
    let after = engine
        .at("world", "obj", 0)
        .transform
        .unwrap_or_else(|| unreachable!("after"));
    close(
        &after,
        &xyz(1.0, 0.0, 0.0),
        "unchanged after rejected reparent",
    );
}
