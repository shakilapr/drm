/// C identifier derived from a topic path or node name (non-alphanumerics
/// become `_`, lowercased, `drm` prefixed). REQ: REQ-TOOL-029.
#[must_use]
pub fn c_ident(identity: &str) -> String {
    let mut out = String::from("drm_");
    for ch in identity.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

/// File-stem identifier derived from a node name (non-alphanumerics become
/// `_`, lowercased). REQ: REQ-TOOL-029.
#[must_use]
pub fn file_ident(identity: &str) -> String {
    let mut out = String::new();
    for ch in identity.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

/// Renders a topic unit in `lang`. REQ: REQ-TOOL-029.
#[must_use]
pub fn topic(lang: Lang, topic: &str, entry: &TopicEntry) -> String {
    match lang {
        Lang::C => topic_c(topic, entry),
        Lang::Cpp => topic_cpp(topic, entry),
        Lang::Rust => topic_rust(topic, entry),
        Lang::Python => topic_python(topic, entry),
    }
}

/// Renders a node-scoped API unit in `lang`. REQ: REQ-TOOL-028.
#[must_use]
pub fn node(lang: Lang, name: &str, entry: &NodeEntry, model: &WorkspaceModel) -> String {
    match lang {
        Lang::C => node_c(name, entry, model),
        Lang::Cpp => node_cpp(name, entry, model),
        Lang::Rust => node_rust(name, entry, model),
        Lang::Python => node_python(name, entry, model),
    }
}

/// C storage type for a canonical primitive. REQ: REQ-TOOL-042.
const fn c_type(p: Prim) -> &'static str {
    match p {
        Prim::Bool | Prim::U8 => "uint8_t",
        Prim::I8 => "int8_t",
        Prim::I16 => "int16_t",
        Prim::U16 => "uint16_t",
        Prim::I32 => "int32_t",
        Prim::U32 => "uint32_t",
        Prim::I64 => "int64_t",
        Prim::U64 => "uint64_t",
        Prim::F32 => "float",
        Prim::F64 => "double",
    }
}

/// Put/get helper suffix for a canonical primitive. REQ: REQ-TOOL-042.
const fn prim_suffix(p: Prim) -> &'static str {
    match p {
        Prim::Bool | Prim::U8 => "u8",
        Prim::I8 => "i8",
        Prim::I16 => "i16",
        Prim::U16 => "u16",
        Prim::I32 => "i32",
        Prim::U32 => "u32",
        Prim::I64 => "i64",
        Prim::U64 => "u64",
        Prim::F32 => "f32",
        Prim::F64 => "f64",
    }
}

/// Include-guard macro for a generated header. REQ: REQ-TOOL-029.
fn guard(prefix: &str) -> String {
    let mut out = String::from("DRM_GEN_C_");
    for ch in prefix.chars() {
        out.push(ch.to_ascii_uppercase());
    }
    out.push_str("_H");
    out
}

/// Emits the generated-file banner. REQ: REQ-TOOL-029.
fn emit_banner(s: &mut String, comment: &str) {
    let _ = writeln!(s, "/* @generated by drm codegen; do not edit. */");
    let _ = writeln!(s, "/* {comment} */");
}

