//! Language renderers for the codegen plan. This slice renders canonical C:
//! per-topic `target.h` (byte layout struct + encode/decode inline functions)
//! and node-scoped API headers exposing only manifest-declared topics.
//! Deterministic: sorted inputs, no timestamps, no absolute paths (I-G1).
//! REQ: REQ-TOOL-029, REQ-TOOL-065, REQ-BIND-011, REQ-BIND-012.

use std::fmt::Write as _;

use crate::canon::{self, Region};
use crate::model::{NodeEntry, TopicEntry, WorkspaceModel};
use crate::parser::{Prim, Type};

use super::{GenKind, Lang, out_path};

/// C identifier derived from a topic path or node name (non-alphanumerics
/// become `_`, lowercased, `drm` prefixed). REQ: REQ-TOOL-029.
#[must_use]
pub fn c_ident(identity: &str) -> String {
    let mut out = String::from("drm_");
    for ch in identity.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

/// File-stem identifier derived from a node name (non-alphanumerics become
/// `_`, lowercased). REQ: REQ-TOOL-029.
#[must_use]
pub fn file_ident(identity: &str) -> String {
    let mut out = String::new();
    for ch in identity.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

/// Renders a topic unit in `lang`. REQ: REQ-TOOL-029.
#[must_use]
pub fn topic(lang: Lang, topic: &str, entry: &TopicEntry) -> String {
    match lang {
        Lang::C => topic_c(topic, entry),
    }
}

/// Renders a node-scoped API unit in `lang`. REQ: REQ-TOOL-028.
#[must_use]
pub fn node(lang: Lang, name: &str, entry: &NodeEntry, model: &WorkspaceModel) -> String {
    match lang {
        Lang::C => node_c(name, entry, model),
    }
}

/// C storage type for a canonical primitive. REQ: REQ-TOOL-042.
const fn c_type(p: Prim) -> &'static str {
    match p {
        Prim::Bool | Prim::U8 => "uint8_t",
        Prim::I8 => "int8_t",
        Prim::I16 => "int16_t",
        Prim::U16 => "uint16_t",
        Prim::I32 => "int32_t",
        Prim::U32 => "uint32_t",
        Prim::I64 => "int64_t",
        Prim::U64 => "uint64_t",
        Prim::F32 => "float",
        Prim::F64 => "double",
    }
}

/// Put/get helper suffix for a canonical primitive. REQ: REQ-TOOL-042.
const fn prim_suffix(p: Prim) -> &'static str {
    match p {
        Prim::Bool | Prim::U8 => "u8",
        Prim::I8 => "i8",
        Prim::I16 => "i16",
        Prim::U16 => "u16",
        Prim::I32 => "i32",
        Prim::U32 => "u32",
        Prim::I64 => "i64",
        Prim::U64 => "u64",
        Prim::F32 => "f32",
        Prim::F64 => "f64",
    }
}

/// Include-guard macro for a generated header. REQ: REQ-TOOL-029.
fn guard(prefix: &str) -> String {
    let mut out = String::from("DRM_GEN_C_");
    for ch in prefix.chars() {
        out.push(ch.to_ascii_uppercase());
    }
    out.push_str("_H");
    out
}

/// Emits the generated-file banner. REQ: REQ-TOOL-029.
fn emit_banner(s: &mut String, comment: &str) {
    let _ = writeln!(s, "/* @generated by drm codegen; do not edit. */");
    let _ = writeln!(s, "/* {comment} */");
}

/// Emits the per-topic endian/geometry helpers (all `static inline`, uniquely
/// prefixed so multiple headers can be included together).
/// REQ: REQ-TOOL-042.
#[allow(clippy::too_many_lines)]
fn emit_helpers(s: &mut String, p: &str) {
    let _ = writeln!(
        s,
        "static inline void {p}_put_u8(uint8_t *d, uint8_t v) {{ d[0] = v; }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_i8(uint8_t *d, int8_t v) {{ d[0] = (uint8_t)v; }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_u16(uint8_t *d, uint16_t v) {{ d[0] = (uint8_t)v; d[1] = (uint8_t)(v >> 8); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_i16(uint8_t *d, int16_t v) {{ {p}_put_u16(d, (uint16_t)v); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_u32(uint8_t *d, uint32_t v) {{ d[0] = (uint8_t)v; d[1] = (uint8_t)(v >> 8); d[2] = (uint8_t)(v >> 16); d[3] = (uint8_t)(v >> 24); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_i32(uint8_t *d, int32_t v) {{ {p}_put_u32(d, (uint32_t)v); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_u64(uint8_t *d, uint64_t v) {{ size_t i; for (i = 0u; i < 8u; i++) {{ d[i] = (uint8_t)(v >> (8u * i)); }} }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_i64(uint8_t *d, int64_t v) {{ {p}_put_u64(d, (uint64_t)v); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_f32(uint8_t *d, float v) {{ uint32_t b; memcpy(&b, &v, sizeof b); {p}_put_u32(d, b); }}"
    );
    let _ = writeln!(
        s,
        "static inline void {p}_put_f64(uint8_t *d, double v) {{ uint64_t b; memcpy(&b, &v, sizeof b); {p}_put_u64(d, b); }}"
    );
    let _ = writeln!(
        s,
        "static inline uint8_t {p}_get_u8(const uint8_t *d) {{ return d[0]; }}"
    );
    let _ = writeln!(
        s,
        "static inline int8_t {p}_get_i8(const uint8_t *d) {{ return (int8_t)d[0]; }}"
    );
    let _ = writeln!(
        s,
        "static inline uint16_t {p}_get_u16(const uint8_t *d) {{ return (uint16_t)((uint16_t)d[0] | ((uint16_t)d[1] << 8)); }}"
    );
    let _ = writeln!(
        s,
        "static inline int16_t {p}_get_i16(const uint8_t *d) {{ return (int16_t){p}_get_u16(d); }}"
    );
    let _ = writeln!(
        s,
        "static inline uint32_t {p}_get_u32(const uint8_t *d) {{ return (uint32_t)d[0] | ((uint32_t)d[1] << 8) | ((uint32_t)d[2] << 16) | ((uint32_t)d[3] << 24); }}"
    );
    let _ = writeln!(
        s,
        "static inline int32_t {p}_get_i32(const uint8_t *d) {{ return (int32_t){p}_get_u32(d); }}"
    );
    let _ = writeln!(
        s,
        "static inline uint64_t {p}_get_u64(const uint8_t *d) {{ uint64_t v = 0u; size_t i; for (i = 0u; i < 8u; i++) {{ v |= (uint64_t)d[i] << (8u * i); }} return v; }}"
    );
    let _ = writeln!(
        s,
        "static inline int64_t {p}_get_i64(const uint8_t *d) {{ return (int64_t){p}_get_u64(d); }}"
    );
    let _ = writeln!(
        s,
        "static inline float {p}_get_f32(const uint8_t *d) {{ uint32_t b = {p}_get_u32(d); float f; memcpy(&f, &b, sizeof f); return f; }}"
    );
    let _ = writeln!(
        s,
        "static inline double {p}_get_f64(const uint8_t *d) {{ uint64_t b = {p}_get_u64(d); double f; memcpy(&f, &b, sizeof f); return f; }}"
    );
    let _ = writeln!(
        s,
        "static inline size_t {p}_align_up(size_t x, size_t a) {{ return (x + (a - 1u)) & ~(a - 1u); }}"
    );
    let _ = writeln!(
        s,
        "static inline int {p}_utf8_valid(const uint8_t *s, size_t n) {{"
    );
    let _ = writeln!(s, "    size_t i = 0u;");
    let _ = writeln!(s, "    while (i < n) {{");
    let _ = writeln!(s, "        uint8_t c = s[i];");
    let _ = writeln!(s, "        size_t need;");
    let _ = writeln!(s, "        if (c < 0x80u) {{ i += 1u; continue; }}");
    let _ = writeln!(s, "        if (c >= 0xC2u && c <= 0xDFu) {{ need = 2u; }}");
    let _ = writeln!(
        s,
        "        else if (c >= 0xE0u && c <= 0xEFu) {{ need = 3u; }}"
    );
    let _ = writeln!(
        s,
        "        else if (c >= 0xF0u && c <= 0xF4u) {{ need = 4u; }}"
    );
    let _ = writeln!(s, "        else {{ return 0; }}");
    let _ = writeln!(s, "        if (i + need > n) {{ return 0; }}");
    let _ = writeln!(
        s,
        "        {{ size_t k; for (k = 1u; k < need; k++) {{ if ((s[i + k] & 0xC0u) != 0x80u) {{ return 0; }} }} }}"
    );
    let _ = writeln!(
        s,
        "        if (c == 0xE0u && s[i + 1u] < 0xA0u) {{ return 0; }}"
    );
    let _ = writeln!(
        s,
        "        if (c == 0xEDu && s[i + 1u] >= 0xA0u) {{ return 0; }}"
    );
    let _ = writeln!(
        s,
        "        if (c == 0xF0u && s[i + 1u] < 0x90u) {{ return 0; }}"
    );
    let _ = writeln!(
        s,
        "        if (c == 0xF4u && s[i + 1u] >= 0x90u) {{ return 0; }}"
    );
    let _ = writeln!(s, "        i += need;");
    let _ = writeln!(s, "    }}");
    let _ = writeln!(s, "    return 1;");
    let _ = writeln!(s, "}}");
}

/// Emits the C struct definition (one member per schema field).
/// REQ: REQ-BIND-011.
fn emit_struct(s: &mut String, p: &str, entry: &TopicEntry) {
    let _ = writeln!(s, "typedef struct {p} {{");
    for field in &entry.schema.fields {
        match &field.ty {
            Type::Prim(prim) => {
                let _ = writeln!(s, "    {} {};", c_type(*prim), field.name);
            }
            Type::Enum { .. } => {
                let _ = writeln!(s, "    uint8_t {};", field.name);
            }
            Type::FixedArray { elem, n } => {
                let _ = writeln!(s, "    {} {}[{}];", c_type(*elem), field.name, n);
            }
            Type::String { max } => {
                let _ = writeln!(s, "    uint32_t {}_len;", field.name);
                let _ = writeln!(s, "    char {}[{}];", field.name, max);
            }
            Type::Bytes { max } => {
                let _ = writeln!(s, "    uint32_t {}_len;", field.name);
                let _ = writeln!(s, "    uint8_t {}[{}];", field.name, max);
            }
            Type::Bounded { elem, max } => {
                let _ = writeln!(s, "    uint32_t {}_len;", field.name);
                let _ = writeln!(s, "    {} {}[{}];", c_type(*elem), field.name, max);
            }
        }
    }
    let _ = writeln!(s, "}} {p};");
}

/// Offset of a fixed (header-region) field. REQ: REQ-TOOL-042.
fn header_offset(entry: &TopicEntry, name: &str) -> u64 {
    entry
        .layout
        .members
        .iter()
        .find(|m| m.region == Region::Header && m.name == name)
        .map_or(0, |m| m.offset)
}

/// Emits the encode write for one fixed field. REQ: REQ-TOOL-042.
fn fixed_write(s: &mut String, p: &str, field: &crate::parser::Field, off: u64) {
    match &field.ty {
        Type::Prim(prim) => {
            let _ = writeln!(
                s,
                "    {p}_put_{}(dst + {off}u, v->{});",
                prim_suffix(*prim),
                field.name
            );
        }
        Type::Enum { .. } => {
            let _ = writeln!(s, "    dst[{off}u] = v->{};", field.name);
        }
        Type::FixedArray { elem, n } => {
            let es = canon::prim_layout(*elem).size;
            let _ = writeln!(
                s,
                "    {{ size_t i; for (i = 0u; i < {n}u; i++) {{ {p}_put_{}(dst + {off}u + i * {es}u, v->{}[i]); }} }}",
                prim_suffix(*elem),
                field.name
            );
        }
        _ => {}
    }
}

/// Emits the decode read for one fixed field. REQ: REQ-TOOL-042.
fn fixed_read(s: &mut String, p: &str, field: &crate::parser::Field, off: u64) {
    match &field.ty {
        Type::Prim(prim) => {
            let _ = writeln!(
                s,
                "    out->{} = {p}_get_{}(src + {off}u);",
                field.name,
                prim_suffix(*prim)
            );
            if *prim == Prim::Bool {
                let _ = writeln!(s, "    if (out->{} > 1u) {{ return 0u; }}", field.name);
            }
        }
        Type::Enum { variants } => {
            let _ = writeln!(s, "    out->{} = src[{off}u];", field.name);
            let _ = writeln!(
                s,
                "    if (out->{} >= {}u) {{ return 0u; }}",
                field.name,
                variants.len()
            );
        }
        Type::FixedArray { elem, n } => {
            let es = canon::prim_layout(*elem).size;
            let _ = writeln!(
                s,
                "    {{ size_t i; for (i = 0u; i < {n}u; i++) {{ out->{}[i] = {p}_get_{}(src + {off}u + i * {es}u); }} }}",
                field.name,
                prim_suffix(*elem)
            );
            if *elem == Prim::Bool {
                let _ = writeln!(
                    s,
                    "    {{ size_t i; for (i = 0u; i < {n}u; i++) {{ if (out->{}[i] > 1u) {{ return 0u; }} }} }}",
                    field.name
                );
            }
        }
        _ => {}
    }
}

/// Variable-member geometry: descriptor offset, element size/alignment, max.
/// REQ: REQ-TOOL-042.
struct VarInfo {
    name: String,
    ty: Type,
    desc_off: u64,
    multi: bool,
    esize: u64,
    ealign: u32,
    max: u64,
}

/// Collects the variable members of a topic in declaration order.
/// REQ: REQ-TOOL-042.
fn variables(entry: &TopicEntry) -> Vec<VarInfo> {
    let names: Vec<&crate::parser::Field> = entry
        .schema
        .fields
        .iter()
        .filter(|f| canon::variable_parts(&f.ty).is_some())
        .collect();
    let multi = names.len() > 1;
    let per: u64 = if multi { 8 } else { 4 };
    let nvar = u64::try_from(names.len()).unwrap_or(0);
    let desc_base = entry.layout.header_end.saturating_sub(nvar * per);
    names
        .iter()
        .enumerate()
        .filter_map(|(i, f)| {
            let (esize, ealign, max) = canon::variable_parts(&f.ty)?;
            Some(VarInfo {
                name: f.name.clone(),
                ty: f.ty.clone(),
                desc_off: desc_base + u64::try_from(i).unwrap_or(0) * per,
                multi,
                esize,
                ealign,
                max,
            })
        })
        .collect()
}

/// Emits the variable-member encode block. REQ: REQ-TOOL-042.
fn variable_write(s: &mut String, p: &str, v: &VarInfo) {
    let _ = writeln!(s, "    {{");
    let _ = writeln!(
        s,
        "        size_t off = {p}_align_up(cursor, {}u);",
        v.ealign
    );
    let _ = writeln!(
        s,
        "        if (v->{}_len > {}u) {{ return 0u; }}",
        v.name, v.max
    );
    let _ = writeln!(
        s,
        "        {p}_put_u32(dst + {}u, v->{}_len);",
        v.desc_off, v.name
    );
    if v.multi {
        let _ = writeln!(
            s,
            "        {p}_put_u32(dst + {}u, (uint32_t)off);",
            v.desc_off + 4
        );
    }
    match &v.ty {
        Type::String { .. } => {
            let _ = writeln!(
                s,
                "        if (!{p}_utf8_valid((const uint8_t *)v->{}, (size_t)v->{}_len)) {{ return 0u; }}",
                v.name, v.name
            );
            let _ = writeln!(
                s,
                "        memcpy(dst + off, v->{}, (size_t)v->{}_len);",
                v.name, v.name
            );
        }
        Type::Bytes { .. } => {
            let _ = writeln!(
                s,
                "        memcpy(dst + off, v->{}, (size_t)v->{}_len);",
                v.name, v.name
            );
        }
        Type::Bounded { elem, .. } => {
            let _ = writeln!(
                s,
                "        {{ size_t i; for (i = 0u; i < (size_t)v->{}_len; i++) {{ {p}_put_{}(dst + off + i * {}u, v->{}[i]); }} }}",
                v.name,
                prim_suffix(*elem),
                v.esize,
                v.name
            );
        }
        _ => {}
    }
    let _ = writeln!(
        s,
        "        cursor = off + (size_t)v->{}_len * {}u;",
        v.name, v.esize
    );
    let _ = writeln!(s, "    }}");
}

/// Emits the variable-member decode block. REQ: REQ-TOOL-042.
fn variable_read(s: &mut String, p: &str, v: &VarInfo) {
    let _ = writeln!(s, "    {{");
    let _ = writeln!(
        s,
        "        uint32_t cnt = {p}_get_u32(src + {}u);",
        v.desc_off
    );
    let _ = writeln!(s, "        if (cnt > {}u) {{ return 0u; }}", v.max);
    let _ = writeln!(
        s,
        "        size_t off = {p}_align_up(cursor, {}u);",
        v.ealign
    );
    if v.multi {
        let _ = writeln!(
            s,
            "        if ({p}_get_u32(src + {}u) != (uint32_t)off) {{ return 0u; }}",
            v.desc_off + 4
        );
    }
    let _ = writeln!(
        s,
        "        if (off > len || (size_t)cnt * {}u > len - off) {{ return 0u; }}",
        v.esize
    );
    let _ = writeln!(s, "        out->{}_len = cnt;", v.name);
    match &v.ty {
        Type::String { .. } => {
            let _ = writeln!(
                s,
                "        if (!{p}_utf8_valid(src + off, (size_t)cnt)) {{ return 0u; }}"
            );
            let _ = writeln!(
                s,
                "        memcpy(out->{}, src + off, (size_t)cnt);",
                v.name
            );
        }
        Type::Bytes { .. } => {
            let _ = writeln!(
                s,
                "        memcpy(out->{}, src + off, (size_t)cnt);",
                v.name
            );
        }
        Type::Bounded { elem, .. } => {
            let _ = writeln!(
                s,
                "        {{ size_t i; for (i = 0u; i < (size_t)cnt; i++) {{ out->{}[i] = {p}_get_{}(src + off + i * {}u); }} }}",
                v.name,
                prim_suffix(*elem),
                v.esize
            );
            if *elem == Prim::Bool {
                let _ = writeln!(
                    s,
                    "        {{ size_t i; for (i = 0u; i < (size_t)cnt; i++) {{ if (out->{}[i] > 1u) {{ return 0u; }} }} }}",
                    v.name
                );
            }
        }
        _ => {}
    }
    let _ = writeln!(s, "        cursor = off + (size_t)cnt * {}u;", v.esize);
    let _ = writeln!(s, "    }}");
}

/// Renders a per-topic C header: banner, guard, helpers, struct, and the
/// canonical two-region encode/decode. REQ: REQ-TOOL-029, REQ-BIND-011.
#[allow(clippy::too_many_lines)]
fn topic_c(topic: &str, entry: &TopicEntry) -> String {
    let p = c_ident(topic);
    let max = entry.layout.sample_max;
    let header_end = entry.layout.header_end;
    let vars = variables(entry);
    let mut s = String::new();
    emit_banner(&mut s, &format!("topic: {topic}"));
    let _ = writeln!(s, "#ifndef {}", guard(&p));
    let _ = writeln!(s, "#define {}", guard(&p));
    let _ = writeln!(s, "#include <stdint.h>");
    let _ = writeln!(s, "#include <stddef.h>");
    let _ = writeln!(s, "#include <string.h>");
    s.push('\n');
    let _ = writeln!(s, "#define {}_SAMPLE_MAX {max}u", p.to_ascii_uppercase());
    s.push('\n');
    emit_helpers(&mut s, &p);
    s.push('\n');
    emit_struct(&mut s, &p, entry);
    s.push('\n');
    let _ = writeln!(
        s,
        "static inline size_t {p}_encode(const {p} *v, uint8_t *dst, size_t cap) {{"
    );
    let _ = writeln!(s, "    if (cap < {max}u) {{ return 0u; }}");
    let _ = writeln!(s, "    memset(dst, 0, {max}u);");
    for field in &entry.schema.fields {
        if canon::variable_parts(&field.ty).is_none() {
            fixed_write(&mut s, &p, field, header_offset(entry, &field.name));
        }
    }
    let _ = writeln!(s, "    {{ size_t cursor = {header_end}u;");
    for v in &vars {
        variable_write(&mut s, &p, v);
    }
    let _ = writeln!(s, "    return cursor; }}");
    let _ = writeln!(s, "}}");
    s.push('\n');
    let _ = writeln!(
        s,
        "static inline size_t {p}_decode({p} *out, const uint8_t *src, size_t len) {{"
    );
    let _ = writeln!(s, "    if (len < {header_end}u) {{ return 0u; }}");
    for field in &entry.schema.fields {
        if canon::variable_parts(&field.ty).is_none() {
            fixed_read(&mut s, &p, field, header_offset(entry, &field.name));
        }
    }
    let _ = writeln!(s, "    {{ size_t cursor = {header_end}u;");
    for v in &vars {
        variable_read(&mut s, &p, v);
    }
    let _ = writeln!(s, "    if (cursor != len) {{ return 0u; }}");
    let _ = writeln!(s, "    return len; }}");
    let _ = writeln!(s, "}}");
    let _ = writeln!(s, "#endif");
    s
}

/// Renders a node-scoped C API header: includes only the node's declared topic
/// headers and exposes typed publish/read wrappers (the sole endpoint layer).
/// REQ: REQ-TOOL-028, REQ-BIND-012.
fn node_c(name: &str, entry: &NodeEntry, model: &WorkspaceModel) -> String {
    let p = c_ident(name);
    let mut s = String::new();
    emit_banner(&mut s, &format!("node: {name}"));
    let _ = writeln!(s, "#ifndef {}", guard(&p));
    let _ = writeln!(s, "#define {}", guard(&p));
    let _ = writeln!(s, "#include <drm/drm.h>");
    let mut topics: Vec<&String> = entry
        .publishes
        .iter()
        .chain(entry.consumes.iter())
        .collect();
    topics.sort_unstable();
    topics.dedup();
    for topic in &topics {
        let rel = out_path(std::path::Path::new(""), Lang::C, GenKind::Topic, topic);
        let rel = rel.to_str().map_or_else(String::new, |r| {
            format!("../{}", r.replace(".drm/gen/c/", ""))
        });
        let _ = writeln!(s, "#include \"{rel}\"");
    }
    s.push('\n');
    for topic in &entry.publishes {
        if !model.topics.contains_key(topic) {
            continue;
        }
        let tp = c_ident(topic);
        let _ = writeln!(
            s,
            "static inline drm_status {p}_publish_{tp}(drm_publisher *pub, const {tp} *v) {{"
        );
        let _ = writeln!(
            s,
            "    uint8_t buf[{}_SAMPLE_MAX];",
            tp.to_ascii_uppercase()
        );
        let _ = writeln!(s, "    size_t n = {tp}_encode(v, buf, sizeof buf);");
        let _ = writeln!(s, "    if (n == 0u) {{ return DRM_ERR_INVALID_DATA; }}");
        let _ = writeln!(s, "    return drm_publish_copy(pub, buf, n);");
        let _ = writeln!(s, "}}");
    }
    for topic in &entry.consumes {
        if !model.topics.contains_key(topic) {
            continue;
        }
        let tp = c_ident(topic);
        let _ = writeln!(
            s,
            "static inline drm_status {p}_read_{tp}(drm_consumer *con, {tp} *out) {{"
        );
        let _ = writeln!(
            s,
            "    uint8_t buf[{}_SAMPLE_MAX];",
            tp.to_ascii_uppercase()
        );
        let _ = writeln!(s, "    size_t n = 0u;");
        let _ = writeln!(
            s,
            "    drm_status st = drm_read_latest(con, buf, sizeof buf, &n);"
        );
        let _ = writeln!(s, "    if (st != DRM_OK) {{ return st; }}");
        let _ = writeln!(
            s,
            "    if ({tp}_decode(out, buf, n) == 0u) {{ return DRM_ERR_INVALID_DATA; }}"
        );
        let _ = writeln!(s, "    return DRM_OK;");
        let _ = writeln!(s, "}}");
    }
    let _ = writeln!(s, "#endif");
    s
}
