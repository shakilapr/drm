//! Pilot packaging dry-run (work-plan M24W2-E4-T1,
//! [qualification.md](../../docs/algorithms/program/qualification.md) §Release
//! Freeze & Pilot Deployment). Assembles the declared pilot bundle set — the
//! workspace crates, the C/C++ headers, the Rust SDK crate, the Python wheel
//! source, and the Studio packages — from their sources per codebase §2.3, so
//! the release packaging dry-run artifacts become the real pilot bundles. Each
//! declared source must resolve; `cargo xtask package --check` fails while a
//! bundle source is missing.
//!
//! REQ: REQ-QAL-026 (pilot packaging).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

/// Kind of pilot bundle.
/// REQ: REQ-QAL-026.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BundleKind {
    /// Workspace crates (`crates/`).
    WorkspaceCrates,
    /// C header + library (`bindings/c`).
    CHeader,
    /// C++ headers (`bindings/cpp`).
    CppHeaders,
    /// Rust SDK crate (`bindings/rust/crates/drm`).
    RustSdk,
    /// Python wheel source (`bindings/python`).
    PythonWheel,
    /// Studio package (`packages/*`).
    StudioPackage,
}

impl BundleKind {
    /// Short label used in the rendered manifest.
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn label(self) -> &'static str {
        match self {
            Self::WorkspaceCrates => "workspace-crates",
            Self::CHeader => "c-header",
            Self::CppHeaders => "cpp-headers",
            Self::RustSdk => "rust-sdk",
            Self::PythonWheel => "python-wheel",
            Self::StudioPackage => "studio-package",
        }
    }
}

/// One declared pilot bundle.
/// REQ: REQ-QAL-026.
pub struct Bundle {
    /// Bundle name.
    pub name: &'static str,
    /// Bundle kind.
    pub kind: BundleKind,
    /// Repository-relative source that must resolve.
    pub source: &'static str,
    /// Package rule citation.
    pub rule: &'static str,
}

