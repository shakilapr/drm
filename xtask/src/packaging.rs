/// Resolution outcome for one bundle.
/// REQ: REQ-QAL-026.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BundleOutcome {
    /// Bundle name.
    pub name: String,
    /// Bundle kind.
    pub kind: BundleKind,
    /// Source path.
    pub source: String,
    /// Package rule citation.
    pub rule: String,
    /// Whether the source resolves under the repository root.
    pub present: bool,
}

/// `BUNDLES_VERIFIED` packaging report.
/// REQ: REQ-QAL-026.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PackagingReport {
    /// One outcome per declared bundle.
    pub bundles: Vec<BundleOutcome>,
}

impl PackagingReport {
    /// Declared bundle count.
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn total(&self) -> usize {
        self.bundles.len()
    }

    /// Bundles whose source resolves.
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn resolved(&self) -> usize {
        self.bundles.iter().filter(|b| b.present).count()
    }

    /// `BUNDLES_VERIFIED` gate: every declared bundle resolves.
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        self.total() > 0 && self.resolved() == self.total()
    }

    /// Renders the dry-run bundle manifest (a generated `@generated` artifact).
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn manifest(&self) -> String {
        let mut out = String::new();
        out.push_str("@generated by cargo xtask package (pilot bundle dry-run); do not edit.\n");
        out.push_str("pilot-bundle-manifest v1\n");
        for bundle in &self.bundles {
            let _ = writeln!(
                out,
                "{}\t{}\t{}",
                bundle.name,
                bundle.kind.label(),
                bundle.source
            );
        }
        out
    }

    /// Renders the report (per-bundle outcome plus the summary).
    /// REQ: REQ-QAL-026.
    #[must_use]
    pub fn render(&self) -> String {
        let mut out = String::new();
        for bundle in &self.bundles {
            let _ = writeln!(
                out,
                "bundle | {} | {} | {} | {} | {}",
                bundle.name,
                bundle.kind.label(),
                if bundle.present {
                    "verified"
                } else {
                    "MISSING"
                },
                bundle.source,
                bundle.rule
            );
        }
        let _ = writeln!(
            out,
            "BUNDLES_VERIFIED = {}/{}",
            self.resolved(),
            self.total()
        );
        out
    }
}

/// Builds the `BUNDLES_VERIFIED` report for the repository rooted at `root`.
/// REQ: REQ-QAL-026.
#[must_use]
pub fn verify(root: &Path) -> PackagingReport {
    let bundles = BUNDLES
        .iter()
        .map(|bundle| BundleOutcome {
            name: bundle.name.to_string(),
            kind: bundle.kind,
            source: bundle.source.to_string(),
            rule: bundle.rule.to_string(),
            present: root.join(bundle.source).exists(),
        })
        .collect();
    PackagingReport { bundles }
}

/// Parsed `xtask package` flags.
#[derive(Debug, Default)]
struct Options {
    check: bool,
    dry_run: bool,
    json: Option<PathBuf>,
}

/// Parses `xtask package` flags.
/// REQ: REQ-QAL-026.
///
/// # Errors
/// [`anyhow::Error`] for unknown flags or a missing `--json` path.
fn parse_options(flags: &[String]) -> Result<Options> {
    let mut options = Options::default();
    let mut i = 0;
    while i < flags.len() {
        match flags[i].as_str() {
            "--check" => options.check = true,
            "--dry-run" => options.dry_run = true,
            "--json" => {
                i += 1;
                let path = flags
                    .get(i)
                    .context("package --json requires a path argument")?;
                options.json = Some(PathBuf::from(path));
            }
            other => bail!(
                "unknown package flag `{other}`; supported: --check, --dry-run, --json <path>"
            ),
        }
        i += 1;
    }
    Ok(options)
}

/// `cargo xtask package [--check] [--dry-run] [--json <path>]`: verify the
/// declared pilot bundle set and render the dry-run bundle manifest; fail
/// (`--check`) while any bundle source is missing. REQ: REQ-QAL-026.
///
/// # Errors
/// [`anyhow::Error`] for unknown flags, an unwritable JSON report or manifest,
/// or a bundle set that does not verify.
pub fn run(flags: &[String]) -> Result<()> {
    let options = parse_options(flags)?;
    let root = repo_root();
    let report = verify(&root);
    print!("{}", report.render());
    if options.dry_run {
        let manifest = root.join("target/pilot-bundle-manifest.txt");
        if let Some(parent) = manifest.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("create {}", parent.display()))?;
        }
        std::fs::write(&manifest, report.manifest())
            .with_context(|| format!("write {}", manifest.display()))?;
        println!("packaging dry-run manifest: {}", manifest.display());
    }
    if let Some(path) = &options.json {
        save(path, &report)?;
    }
    if options.check && !report.is_complete() {
        bail!(
            "BUNDLES_VERIFIED = {}/{} (incomplete bundle set)",
            report.resolved(),
            report.total()
        );
    }
    Ok(())
}

/// Writes the packaging report as pretty JSON with a trailing newline.
/// REQ: REQ-QAL-026.
///
/// # Errors
/// [`anyhow::Error`] when the parent directory or file cannot be written.
fn save(path: &Path, report: &PackagingReport) -> Result<()> {
    if let Some(parent) = path.parent()
        && !parent.as_os_str().is_empty()
    {
        std::fs::create_dir_all(parent).with_context(|| format!("create {}", parent.display()))?;
    }
    let bundles: Vec<serde_json::Value> = report
        .bundles
        .iter()
        .map(|b| {
            serde_json::json!({
                "name": b.name,
                "kind": b.kind.label(),
                "source": b.source,
                "rule": b.rule,
                "present": b.present,
            })
        })
        .collect();
    let body = serde_json::json!({
        "bundles": bundles,
        "resolved": report.resolved(),
        "total": report.total(),
        "bundles_verified": report.is_complete(),
    });
    std::fs::write(path, format!("{body:#}\n"))
        .with_context(|| format!("write {}", path.display()))?;
    Ok(())
}

/// Repository root: the `xtask` crate lives at `<root>/xtask`.
/// REQ: REQ-QAL-026.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
}

/// REQ: REQ-QAL-026 — bundle resolution, dry-run manifest, and flag parsing.
#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};

    use super::{BUNDLES, parse_options, verify};

    /// Repository root fixture.
    /// REQ: REQ-QAL-026.
    fn repo_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
    }

    /// REQ: REQ-QAL-026 — the live repository resolves every declared bundle
    /// and the dry-run manifest names each one.
    #[test]
    fn repository_bundles_verify() {
        let report = verify(&repo_root());
        assert_eq!(report.total(), BUNDLES.len());
        assert!(
            report.is_complete(),
            "missing bundles: {:?}",
            report
                .bundles
                .iter()
                .filter(|b| !b.present)
                .map(|b| b.source.clone())
                .collect::<Vec<_>>()
        );
        let manifest = report.manifest();
        assert!(manifest.contains("@generated"), "generated banner");
        for bundle in BUNDLES {
            assert!(manifest.contains(bundle.name), "manifest names bundle");
        }
    }

    /// REQ: REQ-QAL-026 — a missing bundle source is a gap, and an empty root
    /// verifies nothing.
    #[test]
    fn missing_bundle_is_a_gap() {
        let root = std::env::temp_dir().join(format!("drm-pkg-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap_or_else(|e| unreachable!("mkdir: {e}"));
        let report = verify(&root);
        assert!(!report.is_complete(), "empty root resolves no bundles");
        assert_eq!(report.resolved(), 0);
        let _ = std::fs::remove_dir_all(&root);
    }

    /// REQ: REQ-QAL-026 — flag parsing accepts the modes and rejects unknown
    /// flags or a missing `--json` value.
    #[test]
    fn options_parse_flags() {
        let flags: Vec<String> = ["--check", "--dry-run", "--json", "target/p.json"]
            .iter()
            .map(|s| (*s).to_string())
            .collect();
        let options = parse_options(&flags).unwrap_or_else(|e| unreachable!("parse: {e}"));
        assert!(options.check && options.dry_run);
        assert_eq!(options.json, Some(PathBuf::from("target/p.json")));
        assert!(parse_options(&["--bogus".to_string()]).is_err());
        assert!(parse_options(&["--json".to_string()]).is_err());
    }
}
